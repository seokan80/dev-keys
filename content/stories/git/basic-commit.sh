# 변경 사항 기록하기 — content/sets/git/basic-commit.yaml 의 출력을 뽑는 이야기.
# ~/devkeys 폴더에 저장소를 만들고 README.md 를 커밋한 뒤, 고치고 되돌려 본다.

run 'git config --global user.name "Kim Dev"'
run 'git config --global user.email "dev@example.com"'
run 'git config --global init.defaultBranch main'
run 'git init'
quiet 'printf "# DevKeys\n" > README.md'
run 'git status'
run 'git add README.md'
run 'git status --short'
run 'git commit -m "docs: add README"'
quiet 'printf "# DevKeys\nTyping practice for developers\n" > README.md'
run 'git diff'
run 'git add .'
run 'git diff --staged'
run 'git restore --staged README.md'
run 'git status --short'
run 'git add README.md'
run 'git commit -m "docs: describe project"'
run 'git log --oneline'
run 'git show --stat HEAD'
run 'git commit --amend -m "docs: describe the project"'
run 'git log --oneline'
quiet 'printf "oops\n" >> README.md'
run 'git restore README.md'
run 'git reset --soft HEAD~1'
run 'git status --short'
